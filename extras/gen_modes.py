#!/usr/bin/env python3
"""Generates examples/Modes/Modes.ino from the demos of the mode examples.

Each mode example (SKETCHES below) has its demos as functions marked with a comment:

    // @demo Square -> 1st-order LPF (fc = 10 x signal): rounds the edges
    void lowPass() {
      testSignal.begin(MimicTestSignal::SQUARE, SIGNAL_HZ);
      mimic.setFilter1stLPF(SIGNAL_HZ * 10);
    }

A demo function may use only `mimic`, `testSignal`, `SIGNAL_HZ` and the library constants,
and ends with a "}" at the start of a line. Modes.ino gets every demo, renamed
<Sketch>_<function>, and a menu: type a key in the serial monitor to run a demo.

Usage:
    python extras/gen_modes.py          # writes examples/Modes/Modes.ino
    python extras/gen_modes.py --check  # fails if Modes.ino is not up to date
"""
import pathlib
import re
import sys

# Order of the menu
SKETCHES = [
    "Amplifier",
    "Filter1st",
    "FilterBiquad",
    "Comparator",
    "Clipper",
    "ConstantVoltage",
    "Rectifier",
    "Envelope",
    "Integrator",
    "Differentiator",
]
KEYS = "0123456789abcdefghijklmnopqrstuvwxyz"

ROOT = pathlib.Path(__file__).resolve().parents[1]
OUT = ROOT / "examples" / "Modes" / "Modes.ino"

DEMO_RE = re.compile(r"^// @demo ([^\n]+)\n(void (\w+)\(\) \{\n.*?^\}\n)", re.M | re.S)

HEADER = """\
// Modes: every demo of the mode examples in one sketch.
//
// GENERATED by extras/gen_modes.py from the examples {names}.
// Do not edit this file: change those examples and run `python extras/gen_modes.py`.
//
// Wiring: Arduino UNO R4 A0 -> module IN, SDA / SCL / 5V / GND -> module.
// Look at the module OUT (and at A0 for the input) with an oscilloscope.
// Open the serial monitor (115200 baud) and type a key to run a demo; ? shows the menu.

#include <Wire.h>
#include <AnalogMimic.h>
#include <MimicTestSignal.h>

Mimic0x mimic(MIMIC_VDD_5V);
MimicTestSignal testSignal;
const float SIGNAL_HZ = 100.0f;  // test signal frequency: every setting below scales with it
"""

FOOTER = """\

struct Demo {{
  const char *example;
  const char *text;
  void (*run)();
}};

const Demo DEMOS[] = {{
{table}
}};
const int NUM_DEMOS = sizeof(DEMOS) / sizeof(DEMOS[0]);
const char KEYS[] = "{keys}";

void printMenu() {{
  Serial.println("\\n=== Analog Mimic: Modes ===");
  for (int i = 0; i < NUM_DEMOS; i++) {{
    Serial.print(KEYS[i]);
    Serial.print("  ");
    Serial.print(DEMOS[i].example);
    Serial.print(": ");
    Serial.println(DEMOS[i].text);
  }}
}}

void runDemo(int i) {{
  Serial.print("\\n[");
  Serial.print(KEYS[i]);
  Serial.print("] ");
  Serial.print(DEMOS[i].example);
  Serial.print(": ");
  Serial.println(DEMOS[i].text);
  mimic.setVref(mimic.getVdd() / 2);  // the default, in case a demo changed it
  DEMOS[i].run();
}}

void setup() {{
  Serial.begin(115200);
  Wire.begin();
  delay(2000);  // time to open the serial monitor
  if (!mimic.begin(&Wire)) {{
    Serial.println("Analog Mimic not found");
    while (1);
  }}
  printMenu();
  runDemo(0);
}}

void loop() {{
  if (Serial.available() <= 0) return;
  char c = Serial.read();
  if (c == '?') {{
    printMenu();
    return;
  }}
  if (c >= 'A' && c <= 'Z') c = c - 'A' + 'a';
  for (int i = 0; i < NUM_DEMOS; i++) {{
    if (KEYS[i] == c) {{
      runDemo(i);
      return;
    }}
  }}
}}
"""


def c_string(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def generate():
    parts = [HEADER.format(names=", ".join(SKETCHES))]
    table = []
    for name in SKETCHES:
        path = ROOT / "examples" / name / f"{name}.ino"
        src = path.read_text(encoding="utf-8").replace("\r\n", "\n")
        demos = DEMO_RE.findall(src)
        if not demos:
            sys.exit(f"{path}: no // @demo functions")
        parts.append(f"\n// --- {name} ---\n")
        for text, body, func in demos:
            new = f"{name}_{func}"
            parts.append(f"\n// @demo {text}\n" + body.replace(f"void {func}()", f"void {new}()", 1))
            table.append(f"  {{{c_string(name)}, {c_string(text)}, {new}}},")
    if len(table) > len(KEYS):
        sys.exit(f"{len(table)} demos, but only {len(KEYS)} keys")
    parts.append(FOOTER.format(table="\n".join(table), keys=KEYS[: len(table)]))
    return "".join(parts)


def main():
    text = generate()
    if "--check" in sys.argv[1:]:
        current = OUT.read_text(encoding="utf-8").replace("\r\n", "\n") if OUT.exists() else ""
        if current != text:
            sys.exit("examples/Modes/Modes.ino is not up to date: run python extras/gen_modes.py")
        print("Modes.ino is up to date")
        return
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)} ({text.count('@demo')} demos)")


if __name__ == "__main__":
    main()
